const goalLabels = {
  "fat-loss": "Снижение веса",
  muscle: "Набор мышц",
  endurance: "Выносливость",
  mobility: "Мобильность и восстановление",
};

const levelLabels = {
  beginner: "Новичок",
  intermediate: "Средний",
  advanced: "Продвинутый",
};

const goalSelect = document.getElementById("goal");
const levelSelect = document.getElementById("level");
const generateBtn = document.getElementById("generateBtn");
const workoutCard = document.getElementById("workoutCard");

function renderWorkout() {
  const goal = goalSelect.value;
  const level = levelSelect.value;
  const plan = workouts[goal][level];

  const listItems = plan.map((item) => `<li>${item}</li>`).join("");
  workoutCard.innerHTML = `
    <h2>Тренировка: ${goalLabels[goal]}</h2>
    <p class="muted">Уровень: ${levelLabels[level]}</p>
    <ul>${listItems}</ul>
  `;
}

generateBtn.addEventListener("click", renderWorkout);
